def rook(c, x, y, w, colour):
    h = w * (1788.0 / 2000.0); c.saveState(); c.setFillColor(colour)
    tw = w * 0.26; gap = (w - 3 * tw) / 2.0; bh = h * 0.60
    c.rect(x, y, w, bh * 0.5, fill=1, stroke=0)
    for i in range(3):
        c.rect(x + i * (tw + gap), y, tw, bh, fill=1, stroke=0)
    for i in range(2):
        gx = x + tw + i * (tw + gap); p = c.beginPath()
        p.moveTo(gx, y + bh * 0.5); p.lineTo(gx + gap, y + bh * 0.5)
        p.lineTo(gx + gap / 2.0, y + h); p.close()
        c.drawPath(p, fill=1, stroke=0)
    cx = x + tw + gap + tw / 2.0; p = c.beginPath()
    p.moveTo(x + tw + gap, y + bh); p.lineTo(x + 2 * tw + gap, y + bh)
    p.lineTo(cx, y + h * 1.05); p.close()
    c.drawPath(p, fill=1, stroke=0); c.restoreState()


