def wrap(c, text, x, y, mw, font='Helvetica', size=9, lead=12.5, colour=TEXT_DARK):
    c.setFont(font, size); c.setFillColor(colour); line = ''
    for word in text.split(' '):
        t = (line + ' ' + word).strip()
        if c.stringWidth(t, font, size) > mw and line:
            c.drawString(x, y, line); y -= lead; line = word
        else:
            line = t
    if line:
        c.drawString(x, y, line); y -= lead
    return y


def wrap_center(c, text, cx, y, mw, font='Helvetica', size=7.2, lead=9.5, colour=TEXT_LIGHT):
    c.setFont(font, size); c.setFillColor(colour); line = ''
    for word in text.split(' '):
        t = (line + ' ' + word).strip()
        if c.stringWidth(t, font, size) > mw and line:
            c.drawCentredString(cx, y, line); y -= lead; line = word
        else:
            line = t
    if line:
        c.drawCentredString(cx, y, line); y -= lead
    return y


def bullet(c, head, body, y, mw=CW - 4, x=ML + 2):
    c.setFont('Helvetica-Bold', 9); c.setFillColor(GREEN); c.drawString(x, y, head)
    hw = c.stringWidth(head + '  ', 'Helvetica-Bold', 9)
    c.setFont('Helvetica', 9); c.setFillColor(TEXT_DARK)
    line = ''; first = True; xs = x + hw
    for word in body.split(' '):
        t = (line + ' ' + word).strip(); avail = (mw - hw) if first else mw
        if c.stringWidth(t, 'Helvetica', 9) > avail and line:
            c.drawString(xs if first else x, y, line); y -= 12; line = word; first = False
        else:
            line = t
    if line:
        c.drawString(xs if first else x, y, line); y -= 12
    return y - 6


